"""Generate pinned scalar quantization/tables; never loads or runs firmware.

Unary mappings must come from scripts/pose/make_decode_oracle.py's LiteRT
BUILTIN_REF operator slices. No learned CNN weights are copied here.
"""
import argparse
import json
import math
from pathlib import Path
import struct

SOURCE_SHA256 = "cd7cc22fa946e5d146a7b98d496853e1923e22828d3972d579973f27f91bb105"


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def multiplier(real):
    fraction, shift = math.frexp(real)
    fixed = int(math.floor(fraction * (1 << 31) + 0.5))
    if fixed == 1 << 31:
        fixed //= 2
        shift += 1
    assert 0 < fixed < 1 << 31 and -31 <= shift <= 30
    return fixed, shift


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--unary-luts", type=Path, required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    contract = json.loads((root / "movenet_v4_contract.json").read_text())
    assert contract["source_sha256"] == SOURCE_SHA256
    tensors = {t["index"]: t for t in contract["tensors"]}
    luts = json.loads(args.unary_luts.read_text())
    for name in ("259_260", "276_277", "296_299", "299_300"):
        assert len(luts[name]) == 256 and all(-128 <= v <= 127 for v in luts[name])
    output = ["/* Generated by generate_tables.py; fixed MoveNet int8 v4 contract. */"]

    def quant(i):
        t = tensors[i]
        assert len(t["scale"]) == len(t["zero_point"]) == 1
        return t["scale"][0], t["zero_point"][0]

    def table(name, values):
        output.append(f"static const int8_t {name}[{len(values)}] = {{")
        for i in range(0, len(values), 24):
            output.append("    " + ", ".join(str(v) for v in values[i:i + 24]) + ",")
        output.append("};")

    for op in contract["operators"]:
        index, kind = op["index"], op["op"]
        if kind not in ("ADD", "SUB", "MUL") or index in (94, 95, 125, 135, 136, 148):
            continue
        a, b = op["inputs"]
        c, = op["outputs"]
        sa, za = quant(a)
        sb, zb = quant(b)
        sc, zc = quant(c)
        if kind == "MUL":
            mult, shift = multiplier(sa * sb / sc)
            output.append(f"static const mn_mul_params mn_op{index} = {{{za}, {zb}, {zc}, {mult}, {shift}}};")
        else:
            twice = 2.0 * max(sa, sb)
            ma, sha = multiplier(sa / twice)
            mb, shb = multiplier(sb / twice)
            mo, sho = multiplier(twice / ((1 << 20) * sc))
            output.append(f"static const mn_add_params mn_op{index} = {{{za}, {zb}, {zc}, {ma}, {sha}, {mb}, {shb}, {mo}, {sho}}};")
    sa, za = quant(277)
    sb, zb = quant(278)
    mult, shift = multiplier(sa / sb)
    output.append(f"static const mn_requant_params mn_op104 = {{{za}, {zb}, {mult}, {shift}}};")
    table("mn_center_sigmoid", luts["259_260"])
    table("mn_heatmap_sigmoid", luts["276_277"])
    table("mn_distance_denominator", [luts["299_300"][v + 128] for v in luts["296_299"]])
    table("mn_center_prior", tensors[154]["constant"])
    for tensor, name in ((266, "mn_center_y"), (271, "mn_center_x"), (308, "mn_grid")):
        scale, zero = quant(tensor)
        table(name, [max(-128, min(127, math.floor(f32(i / scale) + 0.5) + zero)) for i in range(48)])
    grid = tensors[171]["constant"][:48]
    assert tensors[171]["constant"] == grid * 48
    assert tensors[170]["constant"] == [v for v in grid for _ in range(48)]
    scale, zero = quant(308)
    assert grid == [max(-128, min(127, math.floor(f32(i / scale) + 0.5) + zero)) for i in range(48)]
    for tensor in (277, 300, 303, 331):
        scale, zero = quant(tensor)
        output.append(f"#define MN_SCALE_{tensor} {float(scale).hex()}f")
        output.append(f"#define MN_ZERO_{tensor} ({zero})")
    assert tensors[173]["constant"] == [127, 127]
    (root / "movenet_v4_tables.inc").write_text("\n".join(output) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
