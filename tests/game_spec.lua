-- Append after app/game.lua and run with the official headless simulator.
local function eq(actual, expected, name)
    assert(actual == expected, name .. ": expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local function advance(game, milliseconds)
    while milliseconds > 0 do
        local chunk = math.min(5000, milliseconds)
        game.update(chunk)
        milliseconds = milliseconds - chunk
    end
end
local function close_walk(game)
    assert(game.finish_walk())
    local ok, result = game.claim_walk()
    assert(ok)
    return result
end

function on_start()
    local game = create_game({timer_rice_ms = 10000, random = function() return 3 end})
    eq(game.snapshot().rice, 3, "starter rice")
    assert(game.feed())
    eq(game.snapshot().rice, 2, "feed consumes one")
    eq(game.snapshot().satiety, 68, "feed raises satiety")
    assert(game.feed())
    assert(game.feed())
    local ok, reason = game.feed()
    eq(ok, false, "no negative inventory")
    eq(reason, "no_rice", "empty reason")

    local full = create_game({saved = {v = 1, rice = 5, satiety = 100}})
    eq(full.feed(), false, "full pet refuses extra food")
    eq(full.snapshot().rice, 5, "full pet does not consume rice")

    assert(game.start_walk("timer"))
    advance(game, 6000)
    eq(game.snapshot().pending_rice, 0, "active reward estimate is numeric")
    assert(game.pause_walk())
    advance(game, 20000)
    eq(game.snapshot().elapsed_ms, 6000, "paused time excluded")
    eq(game.snapshot().step_count, 0, "time never fabricates steps")
    eq(game.set_steps(42), false, "timer source rejects steps")
    assert(game.resume_walk())
    advance(game, 5000)
    assert(game.finish_walk())
    assert(game.finish_walk())
    local before = game.export()
    local restored = create_game({saved = before, timer_rice_ms = 10000, random = function() return 6 end})
    local claimed, event = restored.claim_walk()
    eq(claimed, true, "restored pending reward")
    eq(event.rice_added, 1, "timer reward")
    eq(event.source, "timer", "explicit timer provenance")
    eq(event.item, 3, "pending discovery survives restart")
    eq(event.is_new, true, "first discovery")
    eq(restored.claim_walk(), false, "claim is idempotent")
    eq(restored.finish_walk(), false, "finished claim cannot be replayed")
    eq(restored.snapshot().rice, 1, "reward not duplicated")
    eq(restored.snapshot().pending_rice, 0, "claimed screen cannot show a pending reward")
    eq(restored.snapshot().total_steps, 0, "timer total steps stays zero")

    assert(restored.start_walk("timer"))
    advance(restored, 9000)
    event = close_walk(restored)
    eq(event.rice_added, 1, "fractional time carried between sessions")
    eq(event.item, 6, "injected random controls discovery")
    eq(restored.snapshot().collection_count, 2, "collection count")
    assert(restored.start_walk("timer"))
    advance(restored, 10000)
    event = close_walk(restored)
    eq(event.is_new, false, "duplicate discovery marked honestly")
    eq(restored.snapshot().collection_count, 2, "duplicate leaves collection count unchanged")

    local changed_source = create_game({timer_rice_ms = 10000, steps_per_rice = 500})
    assert(changed_source.start_walk("timer"))
    advance(changed_source, 9000)
    close_walk(changed_source)
    assert(changed_source.start_walk("sensor"))
    assert(changed_source.set_steps(100))
    eq(close_walk(changed_source).rice_added, 0, "time remainder cannot turn into measured-step credit")

    local sensor = create_game({steps_per_rice = 500, random = function() return 1 end})
    assert(sensor.start_walk("sensor"))
    assert(sensor.set_steps(250))
    assert(sensor.set_steps(250))
    eq(sensor.set_steps(200), false, "out of order step sample rejected")
    eq(sensor.set_steps(1 / 0), false, "infinite steps rejected")
    eq(sensor.set_steps(2.5), false, "fractional steps rejected")
    advance(sensor, 15000)
    event = close_walk(sensor)
    eq(event.rice_added, 0, "timer does not reward sensor source")
    eq(event.item, 0, "under-threshold session has no discovery")
    assert(sensor.start_walk("sensor"))
    assert(sensor.set_steps(250))
    event = close_walk(sensor)
    eq(event.rice_added, 1, "fractional measured steps carried")
    eq(sensor.snapshot().total_steps, 500, "measured step total")

    local recovered = create_game({saved = {v = 1, rice = -15, mood = 1/0,
        satiety = "many", collection = 1000, total_steps = 0/0,
        session_id = 2, claimed_id = 1, source = "timer", status = "active",
        elapsed_ms = 10000, step_count = 500}})
    eq(recovered.snapshot().rice, 0, "negative stored rice clamped")
    eq(recovered.snapshot().mood, 70, "infinite mood defaults")
    eq(recovered.snapshot().satiety, 50, "wrong type defaults")
    eq(recovered.snapshot().collection, 63, "mask bounded")
    eq(recovered.snapshot().total_steps, 0, "NaN total defaults")
    eq(recovered.snapshot().status, "paused", "active restore requires explicit resume")
    eq(recovered.snapshot().step_count, 0, "timer restore cannot contain fake steps")
    advance(recovered, 10000)
    eq(recovered.snapshot().elapsed_ms, 10000, "restored pause does not earn time")
    local snapshot = recovered.snapshot()
    snapshot.rice = 999
    eq(recovered.snapshot().rice, 0, "snapshot cannot mutate rules")

    local focus = create_game({focus_duration_ms = 10000})
    assert(focus.start_focus())
    eq(focus.start_walk("sensor"), false, "cannot earn focus and walking rewards together")
    advance(focus, 4000)
    assert(focus.pause_focus())
    advance(focus, 10000)
    eq(focus.snapshot().focus_ms, 4000, "paused focus excluded")
    eq(focus.claim_focus(), false, "incomplete focus not rewarded")
    local focus_saved = create_game({focus_duration_ms = 10000, saved = focus.export()})
    eq(focus_saved.snapshot().focus_status, "paused", "focus restoration is paused")
    assert(focus_saved.resume_focus())
    advance(focus_saved, 6000)
    eq(focus_saved.snapshot().focus_status, "finished", "focus completion")
    local got_focus, focus_event = focus_saved.claim_focus()
    eq(got_focus, true, "focus can be claimed")
    eq(focus_event.source, "focus", "focus provenance")
    eq(focus_saved.snapshot().rice, 4, "one rice per focus")
    eq(focus_saved.claim_focus(), false, "focus cannot be claimed twice")
    eq(focus_saved.snapshot().total_steps, 0, "focus cannot create walking steps")
    assert(focus_saved.start_focus())
    advance(focus_saved, 9000)
    assert(focus_saved.cancel_focus())
    eq(focus_saved.claim_focus(), false, "cancelled focus not rewarded")
    eq(focus_saved.snapshot().rice, 4, "cancelling leaves rice unchanged")
    local cancelled = create_game({focus_duration_ms = 10000, saved = focus_saved.export()})
    eq(cancelled.snapshot().focus_status, "cancelled", "cancelled focus stays cancelled after reload")
    eq(cancelled.claim_focus(), false, "restoring cancellation never rewards focus")
    eq(cancelled.snapshot().rice, 4, "restoring cancellation leaves rice unchanged")

    local exported = recovered.export()
    local field_count = 0
    for key, value in pairs(exported) do
        field_count = field_count + 1
        assert(type(key) == "string" and #key <= 32)
        assert(type(value) ~= "table")
    end
    assert(field_count <= 32, "storage field limit")
    assert(#json.encode(exported) <= 1024, "storage byte limit")
    screen.begin(0x163A32)
    screen.text("Game rules: PASS", 16, 32, 0xFFFFFF)
    screen.text("Feeding / time / steps", 16, 68, 0xFFFFFF)
    screen.text("Restore / reward / save", 16, 104, 0xFFFFFF)
    screen.present()
end

