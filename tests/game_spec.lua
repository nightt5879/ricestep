-- Append after app/game.lua and run with the official headless simulator.
local function eq(actual, expected, name)
    assert(actual == expected, name .. ": expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local function advance(game, milliseconds)
    while milliseconds > 0 do
        local chunk = math.min(5000, milliseconds)
        game.update(chunk)
        milliseconds = milliseconds - chunk
    end
end
local function close_walk(game)
    assert(game.finish_walk())
    local ok, result = game.claim_walk()
    assert(ok)
    return result
end

function on_start()
    local game = create_game({timer_rice_ms = 10000, random = function() return 3 end})
    eq(game.snapshot().rice, 3, "starter rice")
    assert(game.feed())
    eq(game.snapshot().rice, 2, "feed consumes one")
    eq(game.snapshot().satiety, 68, "feed raises satiety")
    assert(game.feed())
    assert(game.feed())
    local ok, reason = game.feed()
    eq(ok, false, "no negative inventory")
    eq(reason, "no_rice", "empty reason")

    local full = create_game({saved = {v = 1, rice = 5, satiety = 100}})
    eq(full.feed(), false, "full pet refuses extra food")
    eq(full.snapshot().rice, 5, "full pet does not consume rice")

    assert(game.start_walk("timer"))
    advance(game, 6000)
    eq(game.snapshot().pending_rice, 0, "active reward estimate is numeric")
    assert(game.pause_walk())
    advance(game, 20000)
    eq(game.snapshot().elapsed_ms, 6000, "paused time excluded")
    eq(game.snapshot().step_count, 0, "time never fabricates steps")
    eq(game.set_steps(42), false, "timer source rejects steps")
    assert(game.resume_walk())
    advance(game, 5000)
    assert(game.finish_walk())
    assert(game.finish_walk())
    local before = game.export()
    local restored = create_game({saved = before, timer_rice_ms = 10000, random = function() return 6 end})
    local claimed, event = restored.claim_walk()
    eq(claimed, true, "restored pending reward")
    eq(event.rice_added, 1, "timer reward")
    eq(event.source, "timer", "explicit timer provenance")
    eq(event.item, 3, "pending discovery survives restart")
    eq(event.is_new, true, "first discovery")
    eq(restored.claim_walk(), false, "claim is idempotent")
    eq(restored.finish_walk(), false, "finished claim cannot be replayed")
    eq(restored.snapshot().rice, 1, "reward not duplicated")
    eq(restored.snapshot().pending_rice, 0, "claimed screen cannot show a pending reward")
    eq(restored.snapshot().total_steps, 0, "timer total steps stays zero")

    assert(restored.start_walk("timer"))
    advance(restored, 9000)
    event = close_walk(restored)
    eq(event.rice_added, 1, "fractional time carried between sessions")
    eq(event.item, 6, "injected random controls discovery")
    eq(restored.snapshot().collection_count, 2, "collection count")
    assert(restored.start_walk("timer"))
    advance(restored, 10000)
    event = close_walk(restored)
    eq(event.is_new, false, "duplicate discovery marked honestly")
    eq(restored.snapshot().collection_count, 2, "duplicate leaves collection count unchanged")

    local changed_source = create_game({timer_rice_ms = 10000, steps_per_rice = 500})
    assert(changed_source.start_walk("timer"))
    advance(changed_source, 9000)
    close_walk(changed_source)
    assert(changed_source.start_walk("sensor"))
    assert(changed_source.set_steps(100))
    eq(close_walk(changed_source).rice_added, 0, "time remainder cannot turn into measured-step credit")

    local sensor = create_game({steps_per_rice = 500, random = function() return 1 end})
    assert(sensor.start_walk("sensor"))
    assert(sensor.set_steps(250))
    assert(sensor.set_steps(250))
    eq(sensor.set_steps(200), false, "out of order step sample rejected")
    eq(sensor.set_steps(1 / 0), false, "infinite steps rejected")
    eq(sensor.set_steps(2.5), false, "fractional steps rejected")
    advance(sensor, 15000)
    event = close_walk(sensor)
    eq(event.rice_added, 0, "timer does not reward sensor source")
    eq(event.item, 0, "under-threshold session has no discovery")
    assert(sensor.start_walk("sensor"))
    assert(sensor.set_steps(250))
    event = close_walk(sensor)
    eq(event.rice_added, 1, "fractional measured steps carried")
    eq(sensor.snapshot().total_steps, 500, "measured step total")

    local recovered = create_game({saved = {v = 1, rice = -15, mood = 1/0,
        satiety = "many", collection = 1000, total_steps = 0/0,
        session_id = 2, claimed_id = 1, source = "timer", status = "active",
        elapsed_ms = 10000, step_count = 500}})
    eq(recovered.snapshot().rice, 0, "negative stored rice clamped")
    eq(recovered.snapshot().mood, 70, "infinite mood defaults")
    eq(recovered.snapshot().satiety, 50, "wrong type defaults")
    eq(recovered.snapshot().collection, 63, "mask bounded")
    eq(recovered.snapshot().total_steps, 0, "NaN total defaults")
    eq(recovered.snapshot().status, "paused", "active restore requires explicit resume")
    eq(recovered.snapshot().step_count, 0, "timer restore cannot contain fake steps")
    advance(recovered, 10000)
    eq(recovered.snapshot().elapsed_ms, 10000, "restored pause does not earn time")
    local snapshot = recovered.snapshot()
    snapshot.rice = 999
    eq(recovered.snapshot().rice, 0, "snapshot cannot mutate rules")

    local focus = create_game({focus_duration_ms = 10000})
    assert(focus.start_focus())
    eq(focus.start_walk("sensor"), false, "cannot earn focus and walking rewards together")
    advance(focus, 4000)
    assert(focus.pause_focus())
    advance(focus, 10000)
    eq(focus.snapshot().focus_ms, 4000, "paused focus excluded")
    eq(focus.claim_focus(), false, "incomplete focus not rewarded")
    local focus_saved = create_game({focus_duration_ms = 10000, saved = focus.export(), random = function() return 4 end})
    eq(focus_saved.snapshot().focus_status, "paused", "focus restoration is paused")
    assert(focus_saved.resume_focus())
    advance(focus_saved, 6000)
    eq(focus_saved.snapshot().focus_status, "finished", "focus completion")
    local got_focus, focus_event = focus_saved.claim_focus()
    eq(got_focus, true, "focus can be claimed")
    eq(focus_event.source, "focus", "focus provenance")
    eq(focus_saved.snapshot().rice, 4, "one rice per focus")
    eq(focus_event.item, 4, "focus discovers an existing collectible")
    eq(focus_event.is_new, true, "focus discovery is marked new")
    eq(focus_saved.snapshot().collection_count, 1, "focus fills collection")
    eq(focus_saved.claim_focus(), false, "focus cannot be claimed twice")
    eq(focus_saved.snapshot().collection_count, 1, "repeated focus claim cannot duplicate discovery")
    eq(focus_saved.snapshot().total_steps, 0, "focus cannot create walking steps")
    assert(focus_saved.start_focus())
    advance(focus_saved, 9000)
    assert(focus_saved.cancel_focus())
    eq(focus_saved.claim_focus(), false, "cancelled focus not rewarded")
    eq(focus_saved.snapshot().rice, 4, "cancelling leaves rice unchanged")
    local cancelled = create_game({focus_duration_ms = 10000, saved = focus_saved.export()})
    eq(cancelled.snapshot().focus_status, "cancelled", "cancelled focus stays cancelled after reload")
    eq(cancelled.claim_focus(), false, "restoring cancellation never rewards focus")
    eq(cancelled.snapshot().rice, 4, "restoring cancellation leaves rice unchanged")

    local cooking = create_game({random = function() return 2 end, focus_duration_ms = 1000})
    eq(cooking.snapshot().last_meal, "", "new companion has no invented meal memory")
    eq(create_game({saved = {v = 1, cook_count = 7}}).snapshot().last_meal, "", "old saves have no invented meal memory")
    for _, invalid in ipairs({"delicious", "none", 2, true, {quality = "perfect"}}) do
        eq(create_game({saved = {v = 1, last_meal = invalid}}).snapshot().last_meal, "", "invalid meal memory defaults")
    end
    eq(cooking.claim_cooking(), false, "idle cooking cannot claim")
    assert(cooking.start_cooking())
    eq(cooking.snapshot().rice, 3, "starting cooking costs no rice")
    eq(cooking.start_cooking(), false, "one cooking round at a time")
    eq(cooking.start_focus(), false, "cooking and focus cannot run together")
    eq(cooking.start_walk("sensor"), false, "cooking and walking cannot run together")
    advance(cooking, 1000)
    eq(cooking.snapshot().cooking_position, 50, "indicator center after one second")
    eq(cooking.snapshot().cooking_remaining_ms, 9000, "cooking countdown")
    local stopped, dish = cooking.stop_cooking()
    assert(stopped)
    eq(dish.quality, "perfect", "center yields perfect rice")
    eq(cooking.snapshot().rice, 3, "stopping alone does not award rice")
    eq(cooking.snapshot().last_meal, "", "stopping alone does not settle meal memory")
    eq(cooking.start_cooking(), false, "unclaimed cooking result cannot be overwritten")
    assert(cooking.stop_cooking())
    local cooked, cooked_result = cooking.claim_cooking()
    assert(cooked)
    eq(cooked_result.rice_added, 2, "perfect cooking yields two rice")
    eq(cooked_result.item, 2, "perfect cooking discovers item")
    eq(cooked_result.is_new, true, "perfect cooking discovery is new")
    eq(cooking.snapshot().cook_count, 1, "completed cooking counted")
    eq(cooking.snapshot().perfect_count, 1, "perfect cooking counted")
    eq(cooking.snapshot().last_meal, "perfect", "claim records the completed meal")
    eq(cooking.claim_cooking(), false, "cooking reward is idempotent")
    eq(cooking.snapshot().rice, 5, "repeated cooking claim leaves balance")
    eq(cooking.snapshot().total_steps, 0, "cooking never invents walking steps")
    local cooking_saved = create_game({saved = cooking.export()})
    eq(cooking_saved.snapshot().cooking_status, "idle", "reloading clears transient round")
    eq(cooking_saved.snapshot().cook_count, 1, "cooking count persists")
    eq(cooking_saved.snapshot().perfect_count, 1, "perfect count persists")
    eq(cooking_saved.snapshot().last_meal, "perfect", "last meal persists across reload")
    eq(cooking_saved.claim_cooking(), false, "reloading cannot replay cooking reward")

    -- Exercise both sides of each scored interval using the public timing input.
    local timings = {540, 560, 860, 880, 1120, 1140, 1440, 1460}
    local qualities = {"raw", "good", "good", "perfect", "perfect", "good", "good", "burnt"}
    local amounts = {0, 1, 1, 2, 2, 1, 1, 0}
    for index, milliseconds in ipairs(timings) do
        local round = create_game({random = function() return 2 end})
        assert(round.start_cooking())
        advance(round, milliseconds)
        assert(round.stop_cooking())
        local awarded, result = round.claim_cooking()
        assert(awarded)
        eq(result.quality, qualities[index], "cooking score boundary " .. index)
        eq(result.rice_added, amounts[index], "cooking boundary reward " .. index)
        eq(round.snapshot().last_meal, qualities[index], "all settled qualities become meal memory " .. index)
        eq(create_game({saved = round.export()}).snapshot().last_meal, qualities[index], "all meal memories restore " .. index)
    end
    assert(cooking.start_cooking())
    advance(cooking, 3000)
    eq(cooking.snapshot().cooking_position, 50, "indicator returns through center")
    local mid_round = create_game({saved = cooking.export()})
    eq(mid_round.snapshot().cooking_status, "idle", "reloading active round cancels it")
    eq(mid_round.snapshot().rice, 5, "reload neither charges nor rewards unfinished round")
    eq(mid_round.snapshot().last_meal, "perfect", "unfinished round preserves previous meal memory")
    advance(cooking, 7000)
    eq(cooking.snapshot().cooking_status, "finished", "timeout finishes cooking")
    eq(cooking.snapshot().cooking_quality, "burnt", "timeout cannot score center")
    eq(cooking.snapshot().last_meal, "perfect", "unclaimed timeout preserves previous meal memory")
    local burnt, burnt_result = cooking.claim_cooking()
    assert(burnt)
    eq(burnt_result.rice_added, 0, "timeout awards no rice")
    eq(cooking.snapshot().rice, 5, "timeout does not deduct inventory")
    eq(cooking.snapshot().cook_count, 2, "timeout is one completed attempt")
    eq(cooking.snapshot().perfect_count, 1, "timeout is not perfect")
    eq(cooking.snapshot().last_meal, "burnt", "zero reward still records the burnt meal")

    assert(cooking.start_focus())
    eq(cooking.start_cooking(), false, "active focus blocks cooking")
    assert(cooking.pause_focus())
    assert(cooking.start_cooking())
    eq(cooking.resume_focus(), false, "cooking blocks focus resume")
    advance(cooking, 1000)
    assert(cooking.stop_cooking())
    assert(cooking.claim_cooking())
    assert(cooking.resume_focus())
    advance(cooking, 1000)
    assert(cooking.claim_focus())
    eq(cooking.snapshot().collection_count, 1, "shared discovery does not duplicate owned item")
    eq(cooking.snapshot().focus_count, 1, "focus still completes after cooking break")
    local capped = create_game({saved = {v = 1, rice = 998}, random = function() return 1 end})
    assert(capped.start_cooking())
    advance(capped, 1000)
    assert(capped.stop_cooking())
    local _, capped_result = capped.claim_cooking()
    eq(capped_result.rice_added, 1, "cooking respects rice capacity")
    eq(capped_result.rice_earned, 2, "earned amount differs from stored capacity")
    eq(capped.snapshot().rice, 999, "rice capacity remains bounded")
    local observed_focus = create_game({focus_duration_ms = 10000})
    assert(observed_focus.start_focus())
    observed_focus.update(20, 1000)
    eq(observed_focus.snapshot().focus_ms, 1000, "focus uses observed elapsed time")
    assert(observed_focus.pause_focus())
    observed_focus.update(20, 1000)
    eq(observed_focus.snapshot().focus_ms, 1000, "paused focus ignores observed time")
    assert(observed_focus.start_cooking())
    observed_focus.update(20, 1000)
    eq(observed_focus.snapshot().cooking_elapsed_ms, 20, "cooking uses animation delta")
    eq(observed_focus.snapshot().cooking_position, 1, "cooking position follows rendered time")
    eq(observed_focus.snapshot().focus_ms, 1000, "cooking break leaves paused focus unchanged")

    local desk = create_game({desk_interval_ms = 10000, desk_snooze_ms = 2000})
    eq(create_game().snapshot().desk_interval_ms, 1800000, "default desk interval is 30 minutes")
    eq(create_game().snapshot().desk_snooze_ms, 300000, "default desk snooze is 5 minutes")
    eq(desk.snapshot().desk_status, "off", "desk reminders require explicit start")
    advance(desk, 15000)
    eq(desk.snapshot().desk_status, "off", "elapsed idle time does not infer sitting")
    eq(desk.snooze_desk(), false, "inactive reminder cannot snooze")
    eq(desk.desk_break(), false, "inactive reminder has no break to acknowledge")
    assert(desk.start_desk())
    desk.update(20, 1000)
    eq(desk.snapshot().desk_remaining_ms, 9000, "desk uses observed elapsed time")
    eq(desk.start_desk(), false, "duplicate start cannot reset a running reminder")
    eq(desk.snooze_desk(), false, "snooze requires a due reminder")
    assert(desk.feed())
    eq(desk.snapshot().desk_remaining_ms, 9000, "feeding is not confirmed physical movement")
    assert(desk.pause_desk())
    advance(desk, 10000)
    eq(desk.snapshot().desk_remaining_ms, 9000, "paused desk time excluded")
    assert(desk.resume_desk())
    advance(desk, 8999)
    eq(desk.snapshot().desk_status, "active", "not due before exact boundary")
    eq(desk.update(1).kind, "desk_due", "first crossing generates reminder")
    eq(desk.snapshot().desk_status, "due", "due remains visible")
    eq(desk.update(1000), nil, "due callback is not replayed")
    assert(desk.snooze_desk())
    eq(desk.snapshot().desk_remaining_ms, 2000, "snooze postpones instead of resetting the full interval")
    eq(desk.snooze_desk(), false, "repeated snooze cannot extend a non-due timer")
    desk.update(500)
    local snooze_saved = create_game({saved = desk.export(), desk_interval_ms = 10000, desk_snooze_ms = 2000})
    eq(snooze_saved.snapshot().desk_status, "snooze_paused", "snooze restores paused")
    advance(snooze_saved, 10000)
    eq(snooze_saved.snapshot().desk_remaining_ms, 1500, "reload does not assume elapsed offline presence")
    assert(snooze_saved.resume_desk())
    advance(snooze_saved, 1500)
    eq(snooze_saved.snapshot().desk_status, "due", "restored snooze keeps remaining time")
    local due_saved = create_game({saved = snooze_saved.export(), desk_interval_ms = 10000})
    eq(due_saved.snapshot().desk_status, "due", "due reminder survives reboot")
    eq(due_saved.snapshot().desk_remaining_ms, 0, "due remainder stays zero")
    assert(due_saved.desk_break())
    eq(due_saved.snapshot().desk_remaining_ms, 10000, "explicit break starts a fresh interval")
    due_saved.update(20, 250)
    local active_saved = create_game({saved = due_saved.export(), desk_interval_ms = 10000})
    eq(active_saved.snapshot().desk_status, "paused", "active desk session needs explicit resume after reboot")
    eq(active_saved.snapshot().desk_remaining_ms, 9750, "active desk remainder persists")
    assert(active_saved.stop_desk())
    advance(active_saved, 20000)
    eq(active_saved.snapshot().desk_status, "off", "closed reminder never reactivates on its own")
    eq(create_game({saved = active_saved.export()}).snapshot().desk_status, "off", "closed reminder stays closed on reboot")
    eq(active_saved.snapshot().rice, 2, "all reminder operations grant no food")
    eq(active_saved.snapshot().total_steps, 0, "all reminder operations grant no steps")
    eq(active_saved.snapshot().focus_count, 0, "reminders do not claim focus work")
    for _, bad in ipairs({6, -1, 1.5, "1", true, math.huge, {}}) do
        eq(create_game({saved = {v = 1, desk = bad, desk_left = 1}}).snapshot().desk_status, "off", "invalid reminder mode defaults off")
    end
    local concurrent = create_game({desk_interval_ms = 1000, focus_duration_ms = 1000})
    assert(concurrent.start_desk())
    assert(concurrent.start_focus())
    eq(concurrent.update(1000).kind, "focus_finished", "focus completion retains its existing event")
    eq(concurrent.snapshot().desk_status, "due", "simultaneous focus event cannot lose the reminder")
    eq(concurrent.snapshot().rice, 3, "simultaneous events cannot claim imaginary exercise food")

    -- Stress the full persisted schema with maximum numeric widths, not only a
    -- fresh save. Keep exactly two added scalar fields under the runtime budget.
    local largest = cooking.export()
    for key, value in pairs(largest) do
        if type(value) == "number" and key ~= "v" then largest[key] = 1000000000000 end
    end
    largest.desk, largest.last_meal = 4, "perfect"
    largest.status, largest.source, largest.claimed_id = "paused", "sensor", 999999999
    largest.focus_status, largest.last_new = "cancelled", false
    local exported = create_game({saved = largest}).export()
    local field_count = 0
    for key, value in pairs(exported) do
        field_count = field_count + 1
        assert(type(key) == "string" and #key <= 32)
        assert(type(value) ~= "table")
    end
    eq(field_count, 32, "storage uses exactly 32 scalar fields")
    assert(#json.encode(exported) <= 1024, "storage byte limit")
    eq(exported.desk_status, nil, "derived reminder UI fields are not persisted")
    screen.begin(0x163A32)
    screen.text("Game rules: PASS", 16, 32, 0xFFFFFF)
    screen.text("Feeding / time / steps", 16, 68, 0xFFFFFF)
    screen.text("Restore / reward / save", 16, 104, 0xFFFFFF)
    screen.present()
end

