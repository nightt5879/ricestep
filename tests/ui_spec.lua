-- Append to game + character + main with storage, speech and sound disabled.
-- Test-only injected samples never appear as a production UI action.
local actual_start, actual_tick = on_start, on_tick
local phase = 0
local original_factory = create_game
function create_game(options)
    options.focus_duration_ms = 1000
    options.random = function() return 2 end
    return original_factory(options)
end
local function equal(actual, expected, label)
    assert(actual == expected, label .. ": expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local function double_click()
    on_button_click("function")
    on_button_click("function")
end
local function single_click()
    on_button_click("function")
    actual_tick(350)
end
function on_start()
    actual_start()
    actual_tick(20)
    actual_tick(20)
    equal(ricestep_debug().state.rice, 3, "fresh app rice")
    double_click()
    equal(ricestep_debug().state.rice, 2, "double click feeds")
    single_click()
    equal(ricestep_debug().home_selection, 2, "single click selects focus")
    double_click()
    equal(ricestep_debug().page, "focus", "open focus")
    double_click()
    actual_tick(400)
    double_click()
    equal(ricestep_debug().state.focus_status, "paused", "focus pause")
    actual_tick(700)
    equal(ricestep_debug().state.focus_ms, 400, "paused focus does not count")
    double_click()
    actual_tick(600)
    equal(ricestep_debug().state.focus_status, "claimed", "focus reward automatically claimed")
    equal(ricestep_debug().state.rice, 3, "focus adds exactly one rice")
    double_click()
    actual_tick(100)
    single_click()
    double_click()
    equal(ricestep_debug().page, "focus_confirm", "early end requires confirmation")
    single_click()
    double_click()
    equal(ricestep_debug().state.focus_status, "cancelled", "confirmed early end")
    equal(ricestep_debug().state.rice, 3, "no premature focus reward")
    single_click()
    double_click()
    equal(ricestep_debug().page, "home", "return home")
    single_click()
    double_click()
    equal(ricestep_debug().page, "walk", "open walking")
    double_click()
    equal(ricestep_debug().state.status, "idle", "missing phone data blocks walking")
    assert(on_step_sample(1000, "2026-10-27"))
    double_click()
    equal(ricestep_debug().state.status, "active", "measured walk starts")
    assert(on_step_sample(1240, "2026-10-27"))
    equal(ricestep_debug().state.step_count, 240, "baseline subtracted")
    assert(on_step_sample(1240, "2026-10-27"))
    equal(ricestep_debug().state.step_count, 240, "repeated sample not duplicated")
    equal(on_step_sample(1200, "2026-10-27"), false, "out of order sample ignored")
    assert(on_step_sample(1500, "2026-10-27"))
    phase = 1
end
local function after_expiry()
    equal(ricestep_debug().steps_connected, false, "unchanged sample expires")
    equal(ricestep_debug().state.status, "active", "stale sample does not end an outdoor walk")
    equal(ricestep_debug().state.step_count, 500, "offline time never invents steps")
    on_step_status("offline")
    actual_tick(20)
    equal(ricestep_debug().state.status, "active", "disconnected source preserves outdoor session")
    double_click()
    equal(ricestep_debug().page, "walk_confirm", "offline settlement requires confirmation")
    equal(ricestep_debug().state.status, "active", "confirmation preserves session")
    equal(ricestep_debug().state.rice, 3, "no reward before confirmation")
    double_click()
    equal(ricestep_debug().page, "walk", "declining offline settlement returns to walk")
    single_click()
    double_click()
    equal(ricestep_debug().page, "home", "offline walk can return home")
    equal(ricestep_debug().state.status, "active", "returning home keeps original baseline")
    double_click()
    assert(on_step_sample(1600, "2026-10-27"))
    equal(ricestep_debug().state.step_count, 600, "return-home sample uses the original baseline")
    assert(on_step_sample(20, "2026-10-28"))
    equal(ricestep_debug().state.step_count, 620, "midnight preserves previously synchronized steps")
    equal(on_step_sample(1900, "2026-10-27"), false, "old day ignored")
    double_click()
    equal(ricestep_debug().page, "summary", "walk completion summary")
    equal(ricestep_debug().state.rice, 4, "measured walking reward")
    equal(ricestep_debug().state.collection_count, 1, "exploration discovery")
    double_click()
    double_click()
    double_click()
    assert(on_step_sample(120, "2026-10-28"))
    equal(ricestep_debug().state.step_count, 100, "next walk establishes new baseline")
    on_step_status("offline")
    double_click()
    single_click()
    double_click()
    equal(ricestep_debug().page, "summary", "explicit offline settlement exits walk")
    equal(ricestep_debug().state.total_steps, 720, "offline claim only uses already measured steps")
    equal(ricestep_debug().state.step_carry, 220, "unredeemed measured steps carry forward")
    double_click()
    single_click()
    double_click()
    equal(ricestep_debug().page, "bag", "open collection")
    for index = 1, 5 do single_click() end
    double_click()
    equal(ricestep_debug().page, "home", "leave collection with single button")
    equal(ricestep_debug().state.total_steps, 720, "only measured samples create steps")
end
function on_tick(dt_ms)
    -- Spread the 95-second freshness exercise over separate runtime callbacks.
    if phase >= 1 and phase <= 19 then
        actual_tick(5000)
        phase = phase + 1
    elseif phase == 20 then
        after_expiry()
        phase = 21
    else actual_tick(dt_ms) end
end
