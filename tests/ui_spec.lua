-- Exercise the real single-button UI; short focus duration is test-only.
local actual_start, actual_tick = on_start, on_tick
local phase = 0
local original_factory = create_game
function create_game(options)
    options.focus_duration_ms = 1000
    local roll = 0
    options.random = function() roll = roll % 6 + 1; return roll end
    return original_factory(options)
end
local function equal(actual, expected, label)
    assert(actual == expected, label .. ": expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local function double_click()
    on_button_click("function")
    on_button_click("function")
end
local function single_click()
    on_button_click("function")
    actual_tick(350)
end
function on_start()
    actual_start()
    actual_tick(20)
    actual_tick(20)
    equal(ricestep_debug().state.rice, 3, "fresh app rice")
    on_button_click("other")
    equal(ricestep_debug().home_selection, 1, "unmapped buttons do not navigate")
    double_click()
    equal(ricestep_debug().state.rice, 2, "double click feeds")
    equal(ricestep_debug().pose, 2, "feeding starts sniff-eat-satisfied sequence")
    single_click()
    equal(ricestep_debug().home_selection, 2, "single click selects focus")
    double_click()
    equal(ricestep_debug().page, "focus", "open focus")
    double_click()
    actual_tick(400)
    double_click()
    equal(ricestep_debug().state.focus_status, "paused", "focus pause")
    actual_tick(700)
    equal(ricestep_debug().state.focus_ms, 400, "paused focus does not count")
    double_click()
    actual_tick(600)
    equal(ricestep_debug().state.focus_status, "claimed", "focus reward automatically claimed")
    equal(ricestep_debug().state.rice, 3, "focus adds exactly one rice")
    equal(ricestep_debug().state.collection_count, 1, "focus discovers a collectible")
    double_click()
    actual_tick(100)
    single_click()
    double_click()
    equal(ricestep_debug().page, "focus_confirm", "early end requires confirmation")
    single_click()
    double_click()
    equal(ricestep_debug().state.focus_status, "cancelled", "confirmed early end")
    equal(ricestep_debug().state.rice, 3, "no premature focus reward")
    single_click()
    double_click()
    equal(ricestep_debug().page, "home", "return home")
    single_click()
    double_click()
    equal(ricestep_debug().page, "cook", "third home option opens cooking")
    double_click()
    equal(ricestep_debug().state.cooking_status, "active", "double confirm starts a round")
    on_button_click("function")
    equal(ricestep_debug().state.cooking_status, "active", "start-click tail ignored during arming")
    phase = 1
end
function on_tick(dt_ms)
    if phase == 1 then
        actual_tick(1000)
        equal(ricestep_debug().state.cooking_position, 50, "visible heat reaches target")
        on_button_click("function")
        equal(ricestep_debug().page, "cook_result", "one release stops the heat immediately")
        equal(ricestep_debug().state.cooking_status, "claimed", "cooking result claimed once")
        equal(ricestep_debug().state.cooking_quality, "perfect", "center hit gives perfect rice")
        equal(ricestep_debug().state.rice, 5, "perfect cooking adds two rice")
        equal(ricestep_debug().state.collection_count, 2, "perfect cooking discovers another collectible")
        equal(ricestep_debug().state.cook_count, 1, "one completed cooking round")
        equal(ricestep_debug().state.perfect_count, 1, "perfect count recorded")
        equal(ricestep_debug().state.last_meal, "perfect", "perfect meal remembered by UI claim")
        double_click()
        equal(ricestep_debug().page, "cook_result", "trailing clicks cannot restart result")
        equal(ricestep_debug().state.rice, 5, "trailing clicks cannot duplicate rice")
        actual_tick(600)
        double_click()
        equal(ricestep_debug().state.cooking_status, "active", "explicit retry after cooldown starts a round")
        phase = 2
    elseif phase == 2 then
        actual_tick(5000)
        actual_tick(5000)
        equal(ricestep_debug().page, "cook_result", "unattended cooking ends automatically")
        equal(ricestep_debug().state.cooking_quality, "burnt", "deadline burns the rice")
        equal(ricestep_debug().state.rice, 5, "burnt rice neither earns nor spends inventory")
        equal(ricestep_debug().state.cook_count, 2, "timeout records one completed round")
        equal(ricestep_debug().state.perfect_count, 1, "timeout cannot increase perfect count")
        equal(ricestep_debug().state.last_meal, "burnt", "timeout replaces previous meal memory")
        equal(ricestep_debug().pose, 6, "burnt meal has sheepish expression")
        actual_tick(600)
        single_click()
        double_click()
        equal(ricestep_debug().page, "home", "cooking result can return home")
        single_click()
        double_click()
        equal(ricestep_debug().page, "bag", "fourth home option opens collection")
        for index = 1, 5 do single_click() end
        double_click()
        equal(ricestep_debug().page, "home", "leave collection with single button")
        for index = 1, 3 do single_click() end
        double_click()
        equal(ricestep_debug().line, "上次饭晒黑了，这回盯紧", "kitchen remembers previous burnt rice")
        equal(ricestep_debug().state.total_steps, 0, "companion activities never invent walking steps")
        phase = 3
    else actual_tick(dt_ms) end
end
