const hash = data => crypto.createHash('sha256').update(data).digest('hex');

function loadPack(assetRoot = DEFAULT_ROOT) {
  const root = fs.realpathSync(assetRoot);
  const manifestPath = fs.realpathSync(path.join(root, 'manifest.json'));
  if (path.dirname(manifestPath) !== root) throw new Error('Manifest must be inside the voice pack.');
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  if (manifest.version !== 1 || !Array.isArray(manifest.clips) || manifest.clips.length !== Object.keys(APPROVED).length) {
    throw new Error('Expected the exact fourteen-clip voice manifest version 1.');
  }
  const seen = new Set();
  const clips = manifest.clips.map(clip => {
    if (!clip || !/^[a-z][a-z0-9_]{0,31}$/.test(clip.id) ||
        !Object.hasOwn(APPROVED, clip.id) || seen.has(clip.id) || clip.file !== `${clip.id}.mp3`) {
      throw new Error('Unknown, duplicate or invalid voice ID/file.');
    }
    seen.add(clip.id);
    const [expectedHash, expectedBytes] = APPROVED[clip.id];
    if (clip.sha256 !== expectedHash || clip.bytes !== expectedBytes) {
      throw new Error(`Manifest differs from reviewed voice bytes: ${clip.id}`);
    }
    if (!Number.isSafeInteger(clip.duration_ms) || clip.duration_ms < 1 || clip.duration_ms > 60000 ||
        clip.sample_rate !== 24000 || clip.channels !== 1) {
      throw new Error(`Invalid MP3 metadata: ${clip.id}`);
    }
    const file = fs.realpathSync(path.join(root, clip.file));
    if (path.dirname(file) !== root) throw new Error(`Clip must be inside the voice pack: ${clip.id}`);
    const info = fs.statSync(file);
    if (!info.isFile() || info.size !== expectedBytes) throw new Error(`Invalid MP3 file size: ${clip.id}`);
    const data = fs.readFileSync(file);
    if (data.length !== expectedBytes || hash(data) !== expectedHash) {
      throw new Error(`MP3 bytes differ from reviewed voice: ${clip.id}`);
    }
    return { id: clip.id, bytes: data.length, sha256: expectedHash, duration_ms: clip.duration_ms, data };
  });
  // Stable enum ordering independent of JSON object/list ordering or host locale.
  clips.sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
  return clips;
}

function renderPack(clips) {
  const totalBytes = clips.reduce((sum, clip) => sum + clip.bytes, 0);
  const maxKey = Math.max(...clips.map(clip => clip.id.length));
  const names = clips.map(clip => `RICE_VOICE_${clip.id.toUpperCase()}`);
  const inventory = {
    version: 1, encoding: 'mp3', sample_rate: 24000, channels: 1,
    alignment: 4, total_bytes: totalBytes,
    pack_sha256: hash(clips.map(clip => `${clip.id}\0${clip.bytes}\0${clip.sha256}\n`).join('')),
    clips: clips.map((clip, index) => ({ index, key: clip.id, enum: names[index], bytes: clip.bytes,
      duration_ms: clip.duration_ms, sha256: clip.sha256 })),
  };
  const header = `/* Generated by scripts/generate-native-voice.cjs. Do not edit. */
#ifndef RICESTEP_NATIVE_VOICE_PACK_H
#define RICESTEP_NATIVE_VOICE_PACK_H
#include <stddef.h>
#include <stdint.h>
#ifdef __cplusplus
extern "C" {
#endif

typedef enum {
${names.map((name, index) => `    ${name} = ${index},`).join('\n')}
    RICE_VOICE_COUNT = ${clips.length}
} rice_voice_id;

#define RICE_VOICE_MAX_KEY_LENGTH ${maxKey}u
#define RICE_VOICE_TOTAL_BYTES ${totalBytes}u

typedef struct {
    rice_voice_id id;
    const char *key;
    size_t key_length;
    const uint8_t *data;
    uint32_t size;
    uint32_t duration_ms;
    const char *sha256;
} rice_voice_clip;

/* Static read-only storage; never free/modify. Invalid enum values return NULL. */
const rice_voice_clip *rice_voice_get(rice_voice_id id);
/* A readable byte span, not necessarily NUL-terminated. Exact allowlist only.
 * NULL, zero/oversize lengths, embedded NULs and unknown keys return NULL.
 * The caller must supply at least key_length readable bytes. No allocation. */
const rice_voice_clip *rice_voice_find(const char *key, size_t key_length);

#ifdef __cplusplus
}
#endif
#endif
`;
  const arrays = clips.map(clip => {
    const rows = [];
    for (let start = 0; start < clip.data.length; start += 16) {
      rows.push('    ' + [...clip.data.subarray(start, start + 16)].map(byte => `0x${byte.toString(16).padStart(2, '0')}`).join(', ') + ',');
    }
    return `_Alignas(4) static const uint8_t rice_voice_data_${clip.id}[] RICE_VOICE_STORAGE = {\n${rows.join('\n')}\n};`;
  }).join('\n\n');
  const source = `/* Generated by scripts/generate-native-voice.cjs; exact reviewed MP3 bytes.
 * Link .rodata.ricestep_voice into CPU-readable Flash, not a RAM-copy section. */
#include "voice_pack.h"
#include <string.h>

#if defined(__GNUC__) || defined(__clang__)
#define RICE_VOICE_STORAGE __attribute__((section(".rodata.ricestep_voice")))
#else
#define RICE_VOICE_STORAGE
#endif

${arrays}

static const rice_voice_clip clips[RICE_VOICE_COUNT] = {
${clips.map((clip, index) => `    { ${names[index]}, "${clip.id}", ${clip.id.length}u, rice_voice_data_${clip.id}, ${clip.bytes}u, ${clip.duration_ms}u, "${clip.sha256}" },`).join('\n')}
};

const rice_voice_clip *rice_voice_get(rice_voice_id id) {
    if ((unsigned)id >= (unsigned)RICE_VOICE_COUNT) return NULL;
    return &clips[(unsigned)id];
}

const rice_voice_clip *rice_voice_find(const char *key, size_t key_length) {
    if (!key || !key_length || key_length > RICE_VOICE_MAX_KEY_LENGTH) return NULL;
    for (unsigned i = 0; i < (unsigned)RICE_VOICE_COUNT; ++i) {
        if (clips[i].key_length == key_length && memcmp(key, clips[i].key, key_length) == 0) return &clips[i];
    }
    return NULL;
}
`;
  return { header, source, inventory };
}

function buildPack(assetRoot = DEFAULT_ROOT) {
  return renderPack(loadPack(assetRoot));
}

function generatePack({ assetRoot = DEFAULT_ROOT, outputDir = DEFAULT_OUTPUT } = {}) {
  const result = buildPack(assetRoot); // Validate everything before writing any output.
  fs.mkdirSync(outputDir, { recursive: true });
  fs.writeFileSync(path.join(outputDir, 'voice_pack.h'), result.header, 'utf8');
  fs.writeFileSync(path.join(outputDir, 'voice_pack.c'), result.source, 'utf8');
  fs.writeFileSync(path.join(outputDir, 'voice_pack.inventory.json'), JSON.stringify(result.inventory, null, 2) + '\n', 'utf8');
  return result.inventory;
}

