"""Mirror/export TinyPose NPZ weights with TensorFlow; host research only.

No downloads, camera access, training or firmware integration. Float export is
always available. Full-int8 export requires an explicit representative images
NPZ and provenance JSON; random calibration is never generated by this script.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import zipfile

import numpy as np
import tensorflow as tf

ARCHITECTURE = "ricestep-tiny-pose-v1"
OFFSET_LAYOUT = "interleaved_yx_grid_units"
BN_EPSILON = 1e-3


def build_keras_model():
    """NHWC mirror. Return model and explicit Torch-state-name/layer mapping."""
    mapping = {}
    def conv(x, name, ci, co, kernel=1, stride=1, depthwise=False):
        layer_name = name.replace(".", "_")
        if depthwise:
            layer = tf.keras.layers.DepthwiseConv2D(kernel, strides=stride, padding="same",
                depth_multiplier=1, use_bias=False, name=layer_name + "_conv")
        else:
            layer = tf.keras.layers.Conv2D(co, kernel, strides=stride, padding="same",
                use_bias=False, name=layer_name + "_conv")
        x = layer(x)
        bn = tf.keras.layers.BatchNormalization(epsilon=BN_EPSILON, momentum=0.9,
                                                name=layer_name + "_bn")
        x = bn(x)
        x = tf.keras.layers.ReLU(max_value=6, name=layer_name + "_relu")(x)
        mapping[name] = dict(conv=layer, bn=bn, ci=ci, co=co, kernel=kernel, depthwise=depthwise)
        return x
    def ds(x, name, ci, co, stride=1):
        return conv(conv(x, name + ".dw", ci, ci, 3, stride, True), name + ".pw", ci, co)
    image = tf.keras.Input(batch_size=1, shape=(96, 96, 3), dtype=tf.float32, name="image")
    x = conv(image, "stem", 3, 16, 3, 2)
    skip24 = ds(ds(x, "enc24a", 16, 24, 2), "enc24b", 24, 24)
    skip12 = ds(ds(skip24, "enc48a", 24, 48, 2), "enc48b", 48, 48)
    x = ds(ds(ds(skip12, "enc96a", 48, 96, 2), "enc96b", 96, 96), "enc96c", 96, 96)
    x = conv(x, "neck48", 96, 48)
    x = tf.image.resize(x, [12, 12], method="bilinear", antialias=False, name="up12")
    x = ds(tf.keras.layers.Add(name="skip12_add")([x, skip12]), "dec48", 48, 48)
    x = conv(x, "neck24", 48, 24)
    x = tf.image.resize(x, [24, 24], method="bilinear", antialias=False, name="up24")
    x = ds(tf.keras.layers.Add(name="skip24_add")([x, skip24]), "dec24", 24, 24)
    logits = tf.keras.layers.Conv2D(17, 1, use_bias=True, name="heatmap_logits")
    offsets = tf.keras.layers.Conv2D(34, 1, use_bias=True, name="local_offsets")
    model = tf.keras.Model(image, [logits(x), offsets(x)], name="ricestep_tiny_pose_v1")
    mapping["heatmap"] = dict(head=logits, ci=24, co=17, kernel=1)
    mapping["offset"] = dict(head=offsets, ci=24, co=34, kernel=1)
    return model, mapping


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def checked_npz(path, max_bytes):
    path = Path(path)
    if path.stat().st_size > max_bytes:
        raise ValueError("NPZ exceeds bounded research input size")
    with zipfile.ZipFile(path) as archive:
        entries = archive.infolist()
        if len({entry.filename for entry in entries}) != len(entries):
            raise ValueError("Duplicate NPZ members")
        if sum(entry.file_size for entry in entries) > max_bytes:
            raise ValueError("Expanded NPZ exceeds bounded research input size")
    return np.load(path, allow_pickle=False)


def load_weights(model, mapping, path):
    """Reject unexpected/missing/nonfinite weights and transpose explicit layouts."""
    expected = {"__metadata__"}
    for name, layer in mapping.items():
        if "head" in layer:
            expected.update((name + ".weight", name + ".bias"))
        else:
            expected.add(name + ".conv.weight")
            expected.update(name + ".bn." + suffix for suffix in
                ("weight", "bias", "running_mean", "running_var", "num_batches_tracked"))
    with checked_npz(path, 8 * 1024 * 1024) as state:
        if set(state.files) != expected:
            raise ValueError(f"State keys differ: missing={sorted(expected-set(state.files))}, extra={sorted(set(state.files)-expected)}")
        meta_bytes = state["__metadata__"]
        if meta_bytes.dtype != np.uint8 or meta_bytes.ndim != 1 or meta_bytes.size > 65536:
            raise ValueError("Invalid weights metadata encoding")
        info = json.loads(meta_bytes.tobytes())
        if (info.get("format") != "ricestep-tiny-pose-weights-v1" or
            info.get("architecture") != ARCHITECTURE or info.get("offset_layout") != OFFSET_LAYOUT or
            info.get("bn_epsilon") != BN_EPSILON or info.get("input_layout") != "NCHW" or
            info.get("input_shape") != [1, 3, 96, 96] or info.get("input_range") != [-1, 1]):
            raise ValueError("Weights architecture/coordinate/preprocessing metadata mismatch")
        if not isinstance(info.get("provenance"), dict) or not info["provenance"]:
            raise ValueError("Weights require explicit provenance (untrained is valid for smoke tests)")
        def array(key, shape):
            value = state[key]
            if value.dtype != np.float32 or value.shape != tuple(shape) or not np.isfinite(value).all():
                raise ValueError(f"Invalid float32 state tensor: {key}")
            return value
        for name, layer in mapping.items():
            ci, co, k = layer["ci"], layer["co"], layer["kernel"]
            if "head" in layer:
                weight = array(name + ".weight", (co, ci, k, k)).transpose(2, 3, 1, 0)
                layer["head"].set_weights([weight, array(name + ".bias", (co,))])
                continue
            if layer["depthwise"]:
                weight = array(name + ".conv.weight", (ci, 1, k, k)).transpose(2, 3, 0, 1)
            else:
                weight = array(name + ".conv.weight", (co, ci, k, k)).transpose(2, 3, 1, 0)
            bn = [array(name + ".bn." + suffix, (co,)) for suffix in
                  ("weight", "bias", "running_mean", "running_var")]
            if np.any(bn[3] < 0):
                raise ValueError("Negative BN running variance")
            tracked = state[name + ".bn.num_batches_tracked"]
            if tracked.shape != () or tracked.dtype != np.int64 or int(tracked) < 0:
                raise ValueError("Invalid BN num_batches_tracked")
            layer["conv"].set_weights([weight])
            layer["bn"].set_weights(bn)
    return info


def load_representative(images_path, metadata_path):
    """Explicit, externally prepared real-image calibration; no automatic fallback."""
    info = json.loads(Path(metadata_path).read_text(encoding="utf-8"))
    if (not isinstance(info, dict) or info.get("synthetic") is not False or
        not isinstance(info.get("source"), str) or not info["source"].strip() or
        info.get("preprocessing") != "rgb*(2/255)-1"):
        raise ValueError("Representative provenance must declare real source, synthetic=false, preprocessing=rgb*(2/255)-1")
    with checked_npz(images_path, 256 * 1024 * 1024) as archive:
        if set(archive.files) != {"images"}:
            raise ValueError("Representative NPZ must contain only 'images'")
        images = archive["images"]
    if (images.dtype != np.float32 or images.ndim != 4 or images.shape[1:] != (96, 96, 3) or
        not 16 <= images.shape[0] <= 2048 or not np.isfinite(images).all() or
        float(images.min()) < -1.000001 or float(images.max()) > 1.000001):
        raise ValueError("Representative images must be 16..2048 finite NHWC float32 96px images in [-1,1]")
    if info.get("sample_count") != images.shape[0]:
        raise ValueError("Representative sample_count mismatch")
    digest = sha256(images_path)
    if info.get("npz_sha256") not in (None, digest):
        raise ValueError("Representative NPZ digest mismatch")
    return images, dict(info, npz_sha256=digest,
        representativeness="Source declared by dataset producer; exporter does not certify coverage or model accuracy")


def tflite_profile(data, require_int8=False):
    interpreter = tf.lite.Interpreter(model_content=data, num_threads=1)
    interpreter.allocate_tensors()
    inputs, outputs = interpreter.get_input_details(), interpreter.get_output_details()
    if len(inputs) != 1 or list(inputs[0]["shape"]) != [1, 96, 96, 3]:
        raise ValueError("Unexpected TFLite input")
    if sorted(list(x["shape"]) for x in outputs) != [[1, 24, 24, 17], [1, 24, 24, 34]]:
        raise ValueError("Unexpected TFLite heads")
    tensors = interpreter.get_tensor_details()
    if require_int8 and (inputs[0]["dtype"] != np.int8 or any(x["dtype"] != np.int8 for x in outputs) or
                        any(x["dtype"] in (np.float32, np.float64, np.float16) for x in tensors)):
        raise ValueError("Full-int8 export retained a float tensor or non-int8 public tensor")
    def item(t):
        scales = t["quantization_parameters"]["scales"]
        zeros = t["quantization_parameters"]["zero_points"]
        if require_int8 and (len(scales) != 1 or not np.isfinite(scales).all() or scales[0] <= 0):
            raise ValueError("Invalid public quantization parameters")
        return dict(index=int(t["index"]), name=t["name"], shape=t["shape"].tolist(),
            dtype=np.dtype(t["dtype"]).name, scales=scales.tolist(), zero_points=zeros.tolist())
    return dict(input=item(inputs[0]), outputs=[dict(item(o), role="logits" if o["shape"][-1] == 17 else "offsets") for o in outputs],
                tensor_count=len(tensors)), interpreter


def check_parity(model, reference_path):
    with checked_npz(reference_path, 16*1024*1024) as data:
        if set(data.files) != {"images", "logits", "offsets"}:
            raise ValueError("Parity NPZ must have images/logits/offsets in NHWC")
        arrays = {key: data[key] for key in data.files}
    n = arrays["images"].shape[0]
    for key, shape in (("images", (n,96,96,3)), ("logits", (n,24,24,17)), ("offsets", (n,24,24,34))):
        if arrays[key].dtype != np.float32 or arrays[key].shape != shape or not np.isfinite(arrays[key]).all():
            raise ValueError("Invalid parity array")
    if not 1 <= n <= 32:
        raise ValueError("Parity reference count outside bounded range")
    predictions = [[], []]
    for image in arrays["images"]:
        result = model(image[None], training=False)
        for i in (0,1): predictions[i].append(result[i].numpy())
    report = {}
    for key, actual in zip(("logits", "offsets"), predictions):
        actual = np.concatenate(actual, axis=0)
        expected = arrays[key]
        if not np.allclose(actual, expected, rtol=1e-4, atol=1e-5):
            raise ValueError(f"Torch/Keras {key} parity failed: maxabs={np.max(np.abs(actual-expected))}")
        report[key + "_max_abs"] = float(np.max(np.abs(actual-expected)))
    return dict(report, reference_sha256=sha256(reference_path), count=n), arrays


def export_models(weights, output_dir, *, representative=None, representative_metadata=None, parity_reference=None):
    if bool(representative) != bool(representative_metadata):
        raise ValueError("Full-int8 export requires BOTH representative images and provenance metadata")
    if representative is None and (Path(output_dir)/"student-int8.tflite").exists():
        raise ValueError("Float-only export target contains a previous int8 model; use a fresh output directory")
    images, calibration = (None, None) if representative is None else load_representative(representative, representative_metadata)
    model, mapping = build_keras_model()
    source_info = load_weights(model, mapping, weights)
    parity, reference = (None, None) if parity_reference is None else check_parity(model, parity_reference)
    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS]
    float_data = converter.convert()
    float_info, interpreter = tflite_profile(float_data)
    if reference is not None:
        max_diff = {"logits":0.0, "offsets":0.0}
        for image, logits, offsets in zip(reference["images"], reference["logits"], reference["offsets"]):
            interpreter.set_tensor(float_info["input"]["index"], image[None])
            interpreter.invoke()
            for output in float_info["outputs"]:
                actual = interpreter.get_tensor(output["index"])
                expected = (logits if output["role"] == "logits" else offsets)[None]
                if not np.allclose(actual, expected, rtol=2e-4, atol=2e-5):
                    raise ValueError("Torch/float-TFLite parity failed")
                max_diff[output["role"]] = max(max_diff[output["role"]], float(np.max(np.abs(actual-expected))))
        parity["float_tflite_max_abs"] = max_diff
    int8_data, int8_info = None, None
    if images is not None:
        converter = tf.lite.TFLiteConverter.from_keras_model(model)
        converter.optimizations = [tf.lite.Optimize.DEFAULT]
        converter.representative_dataset = lambda: ([image[None]] for image in images)
        converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
        converter.inference_input_type = tf.int8
        converter.inference_output_type = tf.int8
        int8_data = converter.convert()
        int8_info, integer_interpreter = tflite_profile(int8_data, require_int8=True)
        # Execute one supplied real sample to verify an invokable full-int8 artifact.
        inp = int8_info["input"]
        q = np.clip(np.rint(images[:1]/inp["scales"][0]+inp["zero_points"][0]), -128,127).astype(np.int8)
        integer_interpreter.set_tensor(inp["index"], q)
        integer_interpreter.invoke()
    target = Path(output_dir)
    target.mkdir(parents=True, exist_ok=True)
    (target/"student-float.tflite").write_bytes(float_data)
    float_info.update(bytes=len(float_data), sha256=hashlib.sha256(float_data).hexdigest())
    if int8_data is not None:
        (target/"student-int8.tflite").write_bytes(int8_data)
        int8_info.update(bytes=len(int8_data), sha256=hashlib.sha256(int8_data).hexdigest())
    report = dict(architecture=ARCHITECTURE, research_only=True, tensorflow_version=tf.__version__,
        source_npz_sha256=sha256(weights), source=source_info, offset_layout=OFFSET_LAYOUT,
        exported_layout="NHWC", input_preprocessing="rgb*(2/255)-1", outputs_have_sigmoid=False,
        torch_parity=parity, float=float_info, int8=int8_info, calibration=calibration,
        limitations=["No accuracy certification or Mini3 timing", "No firmware integration", "No TFLM arena measurement"])
    (target/"export.json").write_text(json.dumps(report, indent=2)+"\n", encoding="utf-8")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--weights", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--representative", type=Path)
    parser.add_argument("--representative-metadata", type=Path)
    parser.add_argument("--parity-reference", type=Path)
    args = parser.parse_args()
    report = export_models(args.weights, args.output_dir, representative=args.representative,
        representative_metadata=args.representative_metadata, parity_reference=args.parity_reference)
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
